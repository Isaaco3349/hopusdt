import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const rulesOnly = process.argv.includes("--rules-only");

function req(name) {
  const v = process.env[name]?.trim();
  if (!v && !rulesOnly) {
    console.warn(`[build] Missing ${name} — using placeholder (set in Vercel env for production).`);
    return null;
  }
  return v ?? "";
}

const FEE = Number(process.env.BRIDGE_FEE ?? "1");
const MIN_AMOUNT = Number(process.env.BRIDGE_MIN_AMOUNT ?? "2");
const ADMIN_EMAIL = process.env.BRIDGE_ADMIN_EMAIL?.trim() ?? "YOUR_ADMIN_EMAIL@example.com";

if (!Number.isFinite(FEE) || FEE <= 0) throw new Error("BRIDGE_FEE must be a positive number");
if (!Number.isFinite(MIN_AMOUNT) || MIN_AMOUNT <= FEE) {
  throw new Error("BRIDGE_MIN_AMOUNT must be greater than BRIDGE_FEE");
}

const firebaseConfigJs = `// Generated by scripts/build.mjs — do not edit by hand
import { initializeApp } from "https://www.gstatic.com/firebasejs/10.12.2/firebase-app.js";
import { getFirestore } from "https://www.gstatic.com/firebasejs/10.12.2/firebase-firestore.js";
import { getAuth } from "https://www.gstatic.com/firebasejs/10.12.2/firebase-auth.js";

const firebaseConfig = {
  apiKey: ${JSON.stringify(req("FIREBASE_API_KEY") || "YOUR_API_KEY")},
  authDomain: ${JSON.stringify(req("FIREBASE_AUTH_DOMAIN") || "YOUR_PROJECT.firebaseapp.com")},
  projectId: ${JSON.stringify(req("FIREBASE_PROJECT_ID") || "YOUR_PROJECT")},
  appId: ${JSON.stringify(req("FIREBASE_APP_ID") || "YOUR_APP_ID")}
};

export const app = initializeApp(firebaseConfig);
export const db = getFirestore(app);
export const auth = getAuth(app);

export const APP_NAME = ${JSON.stringify(process.env.BRIDGE_APP_NAME?.trim() || "USDT Hop")};
export const APP_TAGLINE = ${JSON.stringify(
  process.env.BRIDGE_TAGLINE?.trim() || "Send USDT on TRON, receive USDT on BNB Smart Chain."
)};
export const OPERATOR_NOTE = ${JSON.stringify(
  process.env.BRIDGE_OPERATOR_NOTE?.trim() || "Operated by a verified desk partner."
)};
export const SUPPORT_CONTACT = ${JSON.stringify(process.env.BRIDGE_SUPPORT_CONTACT?.trim() || "")};

export const FEE = ${FEE};
export const MIN_AMOUNT = ${MIN_AMOUNT};
export const DEPOSIT_ADDRESS = ${JSON.stringify(
  req("BRIDGE_DEPOSIT_ADDRESS") || "TXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX"
)};
`;

const firestoreRules = `rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function isAdmin() {
      return request.auth != null && request.auth.token.email == ${JSON.stringify(ADMIN_EMAIL)};
    }
    match /bridges/{id} {
      allow create: if request.resource.data.keys().hasOnly(['send','receive','bscAddress','status','createdAt'])
                    && request.resource.data.status == 'verifying'
                    && request.resource.data.send is number
                    && request.resource.data.send >= ${MIN_AMOUNT}
                    && request.resource.data.receive == request.resource.data.send - ${FEE}
                    && request.resource.data.bscAddress.matches('^0x[a-fA-F0-9]{40}$')
                    && request.resource.data.createdAt == request.time;
      allow get: if true;
      allow list, update, delete: if isAdmin();
    }
  }
}
`;

fs.writeFileSync(path.join(root, "public", "firebase-config.js"), firebaseConfigJs);
fs.writeFileSync(path.join(root, "firestore.rules"), firestoreRules);

console.log("[build] Wrote public/firebase-config.js and firestore.rules");
if (!rulesOnly) {
  console.log("[build] Ready for Vercel (output: public/)");
}
